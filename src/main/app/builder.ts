import path from "node:path";
import fs from "node:fs/promises";

const ELEMENT_CLASS_MAP: Record<string, string> = {
  text: "TextInput",
  dropdown: "DropdownInput",
  upload: "UploadFileInput",
  textarea: "TextArea",
  title: "Title",
  section: "Text",
  "copy-text": "Copy",
  empty: "Empty",
};

export type GeneratedArtifacts = {
  slug: string;
  targetDir: string;
  jsonPath: string;
  pythonPath: string;
};

export async function generateEntityArtifacts(
  entity: any,
  outputDir: string,
): Promise<GeneratedArtifacts> {
  const slug = toSlug(entity?.label || "entity");
  const targetDir = path.join(outputDir, slug);
  await fs.mkdir(targetDir, { recursive: true });

  const jsonPath = path.join(targetDir, "entity.json");
  await fs.writeFile(jsonPath, JSON.stringify(entity, null, 2), "utf-8");

  const pythonPath = path.join(targetDir, "plugin.py");
  await fs.writeFile(pythonPath, buildPython(entity), "utf-8");

  return { slug, targetDir, jsonPath, pythonPath };
}

function buildPython(entity: any): string {
  const imports = new Set<string>();
  const elementsLiteral = emitElements(entity?.elements || [], imports);
  const importList = Array.from(imports);
  const importLine =
    importList.length > 0
      ? `from omoika.elements import ${importList.join(", ")}`
      : "";

  const label = pyString(entity?.label || "Entity");
  const color = pyString(entity?.color || "#22C55E99");
  const icon = pyString(entity?.icon || "database-search");
  const description = pyString(entity?.description || "");

  return `# Auto-generated by Omoika Entity Builder
from omoika.plugins import Plugin
${importLine}


class Entity(Plugin):
    label = ${label}
    description = ${description}
    icon = ${icon}
    color = ${color}

    elements = ${elementsLiteral}
`;
}

function emitElements(elements: any[], imports: Set<string>): string {
  const rows = elements.map((entry) => {
    if (Array.isArray(entry)) {
      return `[${entry.map((el) => emitElement(el, imports)).join(", ")}]`;
    }
    return emitElement(entry, imports);
  });

  return `[
        ${rows.join(",\n        ")}
    ]`;
}

function emitElement(element: any, imports: Set<string>): string {
  const type = element?.type || "text";
  const className = ELEMENT_CLASS_MAP[type] || "TextInput";
  imports.add(className);

  if (type === "empty") {
    return "Empty()";
  }

  const args: string[] = [];
  if (element?.label) args.push(`label=${pyString(element.label)}`);
  if (element?.icon) args.push(`icon=${pyString(element.icon)}`);
  if (element?.value !== undefined && type !== "dropdown") {
    args.push(`value=${pyValue(element.value)}`);
  }

  if (type === "dropdown") {
    const options = (element?.options || []).map((option: any) => {
      const optionParts = [`"label": ${pyString(option.label || "")}`];
      if (option.value !== undefined) {
        optionParts.push(`"value": ${pyString(option.value)}`);
      }
      if (option.description !== undefined && option.description !== null) {
        optionParts.push(`"description": ${pyString(option.description)}`);
      }
      return `{ ${optionParts.join(", ")} }`;
    });
    args.push(`options=[${options.join(", ")}]`);
    if (element?.value !== undefined) {
      args.push(`value=${pyValue(element.value)}`);
    }
  }

  if (type === "upload" && element?.accept) {
    args.push(`accept=${pyString(element.accept)}`);
  }

  return `${className}(${args.join(", ")})`;
}

function toSlug(label: string): string {
  return (
    label
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 64) || "entity"
  );
}

function pyString(value: string): string {
  const escaped = String(value)
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n");
  return `"${escaped}"`;
}

function pyValue(value: any): string {
  if (typeof value === "string") return pyString(value);
  if (typeof value === "number" || typeof value === "boolean")
    return String(value);
  if (value === null || value === undefined) return "None";
  return pyString(String(value));
}
